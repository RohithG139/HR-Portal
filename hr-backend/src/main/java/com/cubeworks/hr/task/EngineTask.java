package com.cubeworks.hr.task;

import com.cubeworks.hr.common.AuditableEntity;
import com.cubeworks.hr.employee.Employee;
import jakarta.persistence.*;
import jakarta.persistence.GenerationType;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import java.time.LocalDate;
import java.time.OffsetDateTime;

/**
 * A mirrored record of one human task from the CaseFabric engine, enriched with
 * application-layer metadata for My Tasks display, notifications and the undo window.
 *
 * <p>Maps to {@code hr.engine_task}. After V3 migration the primary key is a surrogate
 * {@code bigint} identity column ({@code id}); the engine-assigned string task ID
 * ({@code engine_task_id varchar(64)}) is kept as a unique column for engine API calls.
 * The entity extends {@link AuditableEntity} rather than {@link com.cubeworks.hr.common.BaseEntity}
 * because {@code created_at} has no DEFAULT in the DDL and must be set explicitly.</p>
 *
 * <p>The {@code created_at} column comes from the {@link AuditableEntity} superclass (it is
 * one of the standard audit columns); the DDL also lists it explicitly with {@code NOT NULL}
 * to make the constraint visible — both refer to the same single column.</p>
 *
 * <p>Undo-window fields ({@code pending_*}): when a user completes a task the service layer
 * does NOT immediately call the engine. Instead it sets {@link #pendingStatus} =
 * {@link PendingStatus#PENDING}, stores the completion payload in {@link #pendingOutput} and
 * records when the window expires in {@link #pendingExecuteAt}. A scheduler calls the engine
 * after the window and sets {@link PendingStatus#EXECUTED}. The user can undo within the
 * window — see R-API-6 and G-03.</p>
 *
 * <p>DB CHECKs enforce:</p>
 * <ul>
 *   <li>{@code (pending_status IS NULL) = (pending_output IS NULL)}</li>
 *   <li>If {@code pending_status IS NOT NULL} then {@code pending_by} and
 *       {@code pending_execute_at} must also be non-null.</li>
 * </ul>
 */
@Entity
@Table(name = "engine_task")
public class EngineTask extends AuditableEntity {

    /**
     * Surrogate primary key — bigint generated by the DB (V3 migration).
     * Used as the path variable in the undo endpoint: {@code POST /api/tasks/{taskId}/undo}.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false, updatable = false)
    private Long id;

    /**
     * The CaseFabric engine task ID — assigned by the engine, not generated by the DB.
     * Unique constraint preserved after V3 migration. Used for engine API calls
     * ({@link com.cubeworks.hr.engine.CaseEngineClient#completeTask}).
     */
    @Column(name = "engine_task_id", length = 64, nullable = false, unique = true)
    private String engineTaskId;

    /**
     * The employee whose case this task belongs to. The engine case ID is available via
     * {@code employee.case_id}; this direct FK avoids a join when filtering tasks by employee.
     * Lazy: the employee object is not needed for task-list rendering (only employee_id is).
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "employee_id", nullable = false)
    private Employee employee;

    /**
     * The engine task name — used to look up the due-date setting in
     * {@code hr.setting} (category {@code TASK_DUE}, code = task name).
     */
    @Column(name = "task_name", length = 100, nullable = false)
    private String taskName;

    /**
     * The employee who owns (must complete) this task.
     * Null means the task has not been assigned to a specific user yet.
     * Lazy: only needed when rendering the task detail or sending assignment notifications.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "owner_employee_id")
    private Employee ownerEmployee;

    /** Due date for completing this task (G-03, R-CM-3). */
    @Column(name = "due_date", nullable = false)
    private LocalDate dueDate;

    /**
     * The entity type that this task relates to (e.g. {@code REVIEW}, {@code CHECKIN},
     * {@code DECISION}, {@code CHECKLIST}). Used by the frontend to construct the deep-link
     * route without a separate table of route mappings.
     */
    @Column(name = "related_entity", length = 30)
    private String relatedEntity;

    /** The ID of the related entity row. */
    @Column(name = "related_id")
    private Long relatedId;

    /**
     * Timestamp when the engine created this task (mirrored from the engine event).
     * NOTE: this field maps to the same {@code created_at} column that the
     * {@link AuditableEntity} superclass also maps. The superclass's {@code createdAt} getter
     * is inherited; this field is NOT re-declared here — the superclass version is used.
     * The DDL lists {@code created_at NOT NULL} explicitly for this table; both sources
     * refer to the same column.
     */
    @Column(name = "completed_at")
    private OffsetDateTime completedAt;

    /** Timestamp when the task-due notification was sent (G-04). */
    @Column(name = "notified_at")
    private OffsetDateTime notifiedAt;

    /** Timestamp when the overdue reminder was sent (G-05). */
    @Column(name = "overdue_reminder_at")
    private OffsetDateTime overdueReminderAt;

    // ── Undo-window fields (R-API-6, G-03) ──────────────────────────────────

    /**
     * The employee who submitted the pending completion (sets the undo window).
     * Non-null when {@link #pendingStatus} is non-null (DB CHECK).
     * Lazy: only needed in the undo-window confirmation screen.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "pending_by")
    private Employee pendingBy;

    /**
     * The completion payload to send to the engine once the undo window expires.
     * Stored as {@code jsonb} so arbitrary task-type-specific output can be captured.
     * Non-null when {@link #pendingStatus} is non-null (DB CHECK).
     *
     * <p>Using {@code @JdbcTypeCode(SqlTypes.JSON)} for correct Hibernate 6 jsonb handling.</p>
     */
    @JdbcTypeCode(SqlTypes.JSON)
    @Column(name = "pending_output", columnDefinition = "jsonb")
    private String pendingOutput;

    /**
     * When the undo window expires and the scheduler should call the engine.
     * Non-null when {@link #pendingStatus} is non-null (DB CHECK).
     */
    @Column(name = "pending_execute_at")
    private OffsetDateTime pendingExecuteAt;

    /**
     * State of the pending completion:
     * {@code null} = task not yet completed or fully committed;
     * {@link PendingStatus#PENDING} = in undo window;
     * {@link PendingStatus#EXECUTED} = engine call succeeded;
     * {@link PendingStatus#UNDONE} = user undid within the window;
     * {@link PendingStatus#FAILED} = engine call failed, will be retried (R-ARC-5).
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "pending_status", length = 10)
    private PendingStatus pendingStatus;

    /**
     * No-arg constructor for JPA, and for application code to construct a new row via the
     * public setters below (this codebase uses plain setters rather than a builder, so the
     * constructor must be reachable from other feature packages, e.g. {@code onboarding}).
     */
    public EngineTask() {}

    // ── Accessors ────────────────────────────────────────────────────────────

    /** Returns the surrogate numeric PK used in the undo endpoint URL. */
    public Long getId() { return id; }

    public String getEngineTaskId() { return engineTaskId; }
    public void setEngineTaskId(final String engineTaskId) { this.engineTaskId = engineTaskId; }

    public Employee getEmployee() { return employee; }
    public void setEmployee(final Employee employee) { this.employee = employee; }

    public String getTaskName() { return taskName; }
    public void setTaskName(final String taskName) { this.taskName = taskName; }

    public Employee getOwnerEmployee() { return ownerEmployee; }
    public void setOwnerEmployee(final Employee ownerEmployee) { this.ownerEmployee = ownerEmployee; }

    public LocalDate getDueDate() { return dueDate; }
    public void setDueDate(final LocalDate dueDate) { this.dueDate = dueDate; }

    public String getRelatedEntity() { return relatedEntity; }
    public void setRelatedEntity(final String relatedEntity) { this.relatedEntity = relatedEntity; }

    public Long getRelatedId() { return relatedId; }
    public void setRelatedId(final Long relatedId) { this.relatedId = relatedId; }

    public OffsetDateTime getCompletedAt() { return completedAt; }
    public void setCompletedAt(final OffsetDateTime completedAt) { this.completedAt = completedAt; }

    public OffsetDateTime getNotifiedAt() { return notifiedAt; }
    public void setNotifiedAt(final OffsetDateTime notifiedAt) { this.notifiedAt = notifiedAt; }

    public OffsetDateTime getOverdueReminderAt() { return overdueReminderAt; }
    public void setOverdueReminderAt(final OffsetDateTime overdueReminderAt) { this.overdueReminderAt = overdueReminderAt; }

    public Employee getPendingBy() { return pendingBy; }
    public void setPendingBy(final Employee pendingBy) { this.pendingBy = pendingBy; }

    public String getPendingOutput() { return pendingOutput; }
    public void setPendingOutput(final String pendingOutput) { this.pendingOutput = pendingOutput; }

    public OffsetDateTime getPendingExecuteAt() { return pendingExecuteAt; }
    public void setPendingExecuteAt(final OffsetDateTime pendingExecuteAt) { this.pendingExecuteAt = pendingExecuteAt; }

    public PendingStatus getPendingStatus() { return pendingStatus; }
    public void setPendingStatus(final PendingStatus pendingStatus) { this.pendingStatus = pendingStatus; }
}
