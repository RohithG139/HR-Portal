package com.cubeworks.hr.employee;

import com.cubeworks.hr.common.BaseEntity;
import com.cubeworks.hr.settings.Department;
import com.cubeworks.hr.settings.JobTitle;
import jakarta.persistence.*;
import java.time.LocalDate;
import java.time.OffsetDateTime;

/**
 * The central domain entity representing one employee and their case in the CaseFabric engine.
 *
 * <p>Maps to {@code hr.employee}. One employee row corresponds to exactly one CaseFabric case
 * (G-01); the {@link #caseId} links them. The case drives lifecycle transitions via the CMMN
 * model; the {@link #stage} column is a cached copy of the current engine stage so that list
 * screens do not need an engine round-trip (R-ARC-1, R-ARC-2, data-model §5).</p>
 *
 * <p>Personal data restrictions (R-DB-4, G-09): no salary, bank-account details or
 * ID-document numbers are stored here.</p>
 *
 * <p>Self-referential FK constraints:</p>
 * <ul>
 *   <li>{@link #manager}: a DB CHECK prevents an employee from being their own manager.</li>
 *   <li>{@link #buddy}: a DB CHECK prevents an employee from being their own buddy.</li>
 * </ul>
 *
 * <p>{@link #privateEmail} is used as the invitation address (ONB-09) and is marked unique
 * at the DB level; see {@link EmployeeRepository#findByPrivateEmail} for the duplicate-check
 * finder.</p>
 */
@Entity
@Table(name = "employee")
public class Employee extends BaseEntity {

    /**
     * Human-readable employee identifier, e.g. {@code E-0031}.
     * Generated by the service layer when the employee row is created; matches the
     * CaseFabric case ID by convention.
     */
    @Column(name = "employee_code", length = 10, nullable = false, unique = true)
    private String employeeCode;

    /**
     * CaseFabric case identifier (UUID string).
     * Null only between the DB commit that creates the employee row and the engine call
     * that starts the case (R-ARC-5). After startup this is always set.
     */
    @Column(name = "case_id", length = 64, unique = true)
    private String caseId;

    @Column(name = "first_name", length = 100, nullable = false)
    private String firstName;

    @Column(name = "last_name", length = 100, nullable = false)
    private String lastName;

    /**
     * Personal (private) e-mail address, used to send the Keycloak invitation (ONB-09).
     * Must be unique — duplicate detection is done in the service layer before the DB
     * constraint fires.
     */
    @Column(name = "private_email", length = 254, nullable = false, unique = true)
    private String privateEmail;

    /** Work e-mail assigned once the Keycloak account is created. May be null initially. */
    @Column(name = "work_email", length = 254, unique = true)
    private String workEmail;

    @Column(name = "mobile_phone", length = 30, nullable = false)
    private String mobilePhone;

    @Column(name = "date_of_birth", nullable = false)
    private LocalDate dateOfBirth;

    @Column(name = "nationality", length = 60)
    private String nationality;

    @Column(name = "street", length = 150, nullable = false)
    private String street;

    @Column(name = "postcode", length = 12, nullable = false)
    private String postcode;

    @Column(name = "city", length = 100, nullable = false)
    private String city;

    @Column(name = "emergency_name", length = 150)
    private String emergencyName;

    @Column(name = "emergency_relationship", length = 60)
    private String emergencyRelationship;

    @Column(name = "emergency_phone", length = 30)
    private String emergencyPhone;

    /**
     * The employee's job title.
     * Lazy: avoid N+1 when listing employees — only fetch when displaying the detail view.
     * N+1 prevention note: the employee list query uses JOIN FETCH to load job_title in one
     * query rather than issuing a separate SELECT per employee row.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "job_title_id", nullable = false)
    private JobTitle jobTitle;

    /**
     * The employee's department.
     * Lazy: same rationale as {@link #jobTitle} — fetched via JOIN FETCH in list queries.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "department_id", nullable = false)
    private Department department;

    /**
     * Seniority grade — stored as varchar with a CHECK constraint (R-DB-2).
     * Fixed enum per the FRD (data-model §6, assumption 1).
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "grade", length = 10, nullable = false)
    private Grade grade;

    /**
     * Line manager of this employee (self-referential FK).
     * Null for employees without a manager (e.g. the CEO or top-level HR staff).
     * A DB CHECK prevents an employee from managing themselves.
     * Lazy: avoid loading the manager object when only the manager_id value is needed.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "manager_id")
    private Employee manager;

    /**
     * Onboarding buddy assigned to this employee (self-referential FK).
     * Null if no buddy has been assigned.
     * A DB CHECK prevents an employee from being their own buddy.
     */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "buddy_id")
    private Employee buddy;

    /**
     * Application role determining which screens and API endpoints the employee can access.
     * Fine-grained checks are enforced at the service layer (R-API-2), not only in the UI.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "app_role", length = 10, nullable = false)
    private AppRole appRole;

    /**
     * Keycloak subject ({@code sub} claim) — set when the Keycloak account is created.
     * Null until the invite is accepted and the account is provisioned.
     */
    @Column(name = "idp_subject", length = 64, unique = true)
    private String idpSubject;

    /** Keycloak account provisioning state. Defaults to {@link AccountStatus#NOT_INVITED}. */
    @Enumerated(EnumType.STRING)
    @Column(name = "account_status", length = 12, nullable = false)
    private AccountStatus accountStatus = AccountStatus.NOT_INVITED;

    /** Timestamp of the employee's first login — set by the Keycloak event handler. */
    @Column(name = "first_login_at")
    private OffsetDateTime firstLoginAt;

    /**
     * Cached copy of the CaseFabric engine stage (R-ARC-1).
     * Written by Spring after every engine stage transition; never computed from DB data.
     * Defaults to {@link EmployeeStage#ONBOARDING} for newly created employees.
     */
    @Enumerated(EnumType.STRING)
    @Column(name = "stage", length = 12, nullable = false)
    private EmployeeStage stage = EmployeeStage.ONBOARDING;

    /** Date on which the current stage began. */
    @Column(name = "stage_since")
    private LocalDate stageSince;

    /**
     * Timestamp when the employee case was archived (G-10).
     * A non-null value means the case is archived and all UI screens are read-only (R-UI-8).
     */
    @Column(name = "archived_at")
    private OffsetDateTime archivedAt;

    /**
     * No-arg constructor for JPA, and for application code to construct a new row via the
     * public setters below (this codebase uses plain setters rather than a builder, so the
     * constructor must be reachable from other feature packages, e.g. {@code onboarding}).
     */
    public Employee() {}

    // ── Accessors ────────────────────────────────────────────────────────────

    public String getEmployeeCode() { return employeeCode; }
    public void setEmployeeCode(final String employeeCode) { this.employeeCode = employeeCode; }

    public String getCaseId() { return caseId; }
    public void setCaseId(final String caseId) { this.caseId = caseId; }

    public String getFirstName() { return firstName; }
    public void setFirstName(final String firstName) { this.firstName = firstName; }

    public String getLastName() { return lastName; }
    public void setLastName(final String lastName) { this.lastName = lastName; }

    public String getPrivateEmail() { return privateEmail; }
    public void setPrivateEmail(final String privateEmail) { this.privateEmail = privateEmail; }

    public String getWorkEmail() { return workEmail; }
    public void setWorkEmail(final String workEmail) { this.workEmail = workEmail; }

    public String getMobilePhone() { return mobilePhone; }
    public void setMobilePhone(final String mobilePhone) { this.mobilePhone = mobilePhone; }

    public LocalDate getDateOfBirth() { return dateOfBirth; }
    public void setDateOfBirth(final LocalDate dateOfBirth) { this.dateOfBirth = dateOfBirth; }

    public String getNationality() { return nationality; }
    public void setNationality(final String nationality) { this.nationality = nationality; }

    public String getStreet() { return street; }
    public void setStreet(final String street) { this.street = street; }

    public String getPostcode() { return postcode; }
    public void setPostcode(final String postcode) { this.postcode = postcode; }

    public String getCity() { return city; }
    public void setCity(final String city) { this.city = city; }

    public String getEmergencyName() { return emergencyName; }
    public void setEmergencyName(final String emergencyName) { this.emergencyName = emergencyName; }

    public String getEmergencyRelationship() { return emergencyRelationship; }
    public void setEmergencyRelationship(final String emergencyRelationship) { this.emergencyRelationship = emergencyRelationship; }

    public String getEmergencyPhone() { return emergencyPhone; }
    public void setEmergencyPhone(final String emergencyPhone) { this.emergencyPhone = emergencyPhone; }

    public JobTitle getJobTitle() { return jobTitle; }
    public void setJobTitle(final JobTitle jobTitle) { this.jobTitle = jobTitle; }

    public Department getDepartment() { return department; }
    public void setDepartment(final Department department) { this.department = department; }

    public Grade getGrade() { return grade; }
    public void setGrade(final Grade grade) { this.grade = grade; }

    public Employee getManager() { return manager; }
    public void setManager(final Employee manager) { this.manager = manager; }

    public Employee getBuddy() { return buddy; }
    public void setBuddy(final Employee buddy) { this.buddy = buddy; }

    public AppRole getAppRole() { return appRole; }
    public void setAppRole(final AppRole appRole) { this.appRole = appRole; }

    public String getIdpSubject() { return idpSubject; }
    public void setIdpSubject(final String idpSubject) { this.idpSubject = idpSubject; }

    public AccountStatus getAccountStatus() { return accountStatus; }
    public void setAccountStatus(final AccountStatus accountStatus) { this.accountStatus = accountStatus; }

    public OffsetDateTime getFirstLoginAt() { return firstLoginAt; }
    public void setFirstLoginAt(final OffsetDateTime firstLoginAt) { this.firstLoginAt = firstLoginAt; }

    public EmployeeStage getStage() { return stage; }
    public void setStage(final EmployeeStage stage) { this.stage = stage; }

    public LocalDate getStageSince() { return stageSince; }
    public void setStageSince(final LocalDate stageSince) { this.stageSince = stageSince; }

    public OffsetDateTime getArchivedAt() { return archivedAt; }
    public void setArchivedAt(final OffsetDateTime archivedAt) { this.archivedAt = archivedAt; }
}
