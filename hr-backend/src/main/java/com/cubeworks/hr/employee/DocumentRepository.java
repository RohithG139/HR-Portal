package com.cubeworks.hr.employee;

import org.springframework.data.jpa.repository.JpaRepository;

import java.util.Optional;

/**
 * Spring Data repository for {@link Document}.
 *
 * <p>Documents are stored as metadata rows in the DB; the file bytes live in the
 * filesystem (or object storage in production). The {@code storage_key} is the
 * path/UUID used to retrieve the file from the storage layer.</p>
 */
public interface DocumentRepository extends JpaRepository<Document, Long> {

    /**
     * Finds a document by its unique storage key.
     *
     * <p>Used to detect accidental duplicate uploads (programming error — the storage key
     * is generated by the upload service and must be globally unique).</p>
     *
     * @param storageKey the unique storage path/UUID
     * @return the document, if any
     */
    Optional<Document> findByStorageKey(String storageKey);
}
